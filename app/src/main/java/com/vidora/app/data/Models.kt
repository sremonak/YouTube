package com.vidora.app.data

import kotlinx.serialization.Serializable

@Serializable
data class VideoItem(
    val url: String,
    val title: String,
    val thumbnail: String? = null,
    val uploader: String? = null,
    val uploaderUrl: String? = null,
    val uploaderAvatar: String? = null,
    val duration: Long = 0,
    val views: Long = -1,
    val uploadedText: String? = null,
    val uploadedEpoch: Long = 0,
    val isLive: Boolean = false,
    val isShort: Boolean = false,
    val verified: Boolean = false,
)

@Serializable
data class ChannelItem(
    val url: String,
    val name: String,
    val avatar: String? = null,
    val subscribers: Long = -1,
    val description: String? = null,
    val verified: Boolean = false,
)

@Serializable
data class PlaylistItem(
    val url: String,
    val name: String,
    val thumbnail: String? = null,
    val uploader: String? = null,
    val count: Long = -1,
)

/** A single row of any list returned by the content repository. */
sealed interface Entry {
    val key: String

    data class Video(val video: VideoItem) : Entry {
        override val key get() = "v:" + video.url
    }

    data class Channel(val channel: ChannelItem) : Entry {
        override val key get() = "c:" + channel.url
    }

    data class Playlist(val playlist: PlaylistItem) : Entry {
        override val key get() = "p:" + playlist.url
    }
}

/** Simple continuation-style pagination. */
class PageResult(
    val items: List<Entry>,
    val next: (suspend () -> PageResult)? = null,
)

data class VideoOption(
    val url: String,
    val itag: Int,
    val height: Int,
    val fps: Int,
    val resolution: String,
    val mime: String,
    val suffix: String,
    val codec: String?,
    val videoOnly: Boolean,
    val bitrate: Int,
    val contentLength: Long,
) {
    val label: String
        get() = buildString {
            append(if (height > 0) "${height}p" else resolution)
            if (fps > 30) append(fps)
        }
}

data class AudioOption(
    val url: String,
    val itag: Int,
    val bitrateKbps: Int,
    val mime: String,
    val suffix: String,
    val codec: String?,
    val trackName: String?,
    val contentLength: Long,
    val trackId: String? = null,
    val trackType: String? = null,
    val language: String? = null,
) {
    val label: String get() = "${bitrateKbps} kbps · ${suffix.uppercase()}"
}

/** One selectable audio language (original, dubbed, descriptive…). */
data class AudioTrack(val id: String?, val name: String, val type: String?)

data class SubtitleOption(
    val url: String,
    val languageCode: String,
    val label: String,
    val autoGenerated: Boolean,
    val mime: String,
)

/** Storyboard sheet info for seek-bar previews. */
data class FrameSet(
    val urls: List<String>,
    val frameWidth: Int,
    val frameHeight: Int,
    val perPageX: Int,
    val perPageY: Int,
    val durationPerFrame: Int,
    val totalCount: Int,
) {
    /** Returns (sheet url, left, top) for a playback position. */
    fun frameAt(positionMs: Long): Triple<String, Int, Int>? {
        if (urls.isEmpty() || durationPerFrame <= 0 || perPageX <= 0 || perPageY <= 0) return null
        val perSheet = perPageX * perPageY
        val absolute = (positionMs / durationPerFrame).toInt().coerceIn(0, maxOf(totalCount - 1, 0))
        val sheet = (absolute / perSheet).coerceAtMost(urls.size - 1)
        val rel = absolute % perSheet
        return Triple(urls[sheet], (rel % perPageX) * frameWidth, (rel / perPageX) * frameHeight)
    }
}

