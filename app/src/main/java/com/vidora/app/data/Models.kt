data class Chapter(val title: String, val startSeconds: Int, val thumbnail: String?)

data class StreamDetails(
    val item: VideoItem,
    val description: String,
    val likes: Long,
    val subscriberCount: Long,
    val videoStreams: List<VideoOption>,
    val audioStreams: List<AudioOption>,
    val hlsUrl: String?,
    val dashUrl: String?,
    val related: List<Entry>,
    val chapters: List<Chapter>,
    val tags: List<String>,
    val category: String?,
    val allAudioStreams: List<AudioOption> = audioStreams,
    val subtitles: List<SubtitleOption> = emptyList(),
    val frames: FrameSet? = null,
    /** Continuation token for live chat (live streams and chat replays), null if unavailable. */
    val liveChat: String? = null,
) {
    /** Distinct audio languages; empty/one entry means there's nothing to choose. */
    val audioTracks: List<AudioTrack>
        get() = allAudioStreams.distinctBy { it.trackId }.map {
            AudioTrack(it.trackId, it.trackName ?: it.language ?: "Default", it.trackType)
        }

    fun audioFor(trackId: String?): List<AudioOption> =
        if (trackId == null) audioStreams else allAudioStreams.filter { it.trackId == trackId }.ifEmpty { audioStreams }

    /** Muxed (video + audio) progressive streams. */
    val muxed get() = videoStreams.filter { !it.videoOnly }
    val videoOnly get() = videoStreams.filter { it.videoOnly }
    val relatedVideos get() = related.filterIsInstance<Entry.Video>().map { it.video }
}

